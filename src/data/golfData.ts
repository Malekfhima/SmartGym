function makeCompletedHoles(course: Course, scores: number[]): HoleScore[] {
  return course.holes.map((hole, idx) => {
    const strokes = scores[idx] ?? hole.par;
    const diff = strokes - hole.par;
    return {
      holeNumber: hole.number,
      par: hole.par,
      strokes,
      putts: diff <= -1 ? 1 : diff === 0 ? 2 : 2,
      fairway: hole.par === 3 ? null : idx % 4 === 1 ? 'left' : idx % 5 === 2 ? 'right' : 'hit',
      gir: diff <= 0 ? true : idx % 3 === 0,
    };
  });
}

